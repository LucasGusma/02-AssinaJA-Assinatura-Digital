CREATE TABLE APP_SCHEMA.AJA_PERMISSAO (
 CD_USUARIO VARCHAR2(128) PRIMARY KEY,
 SN_TRANSFERIR CHAR(1) DEFAULT 'N' NOT NULL CHECK (SN_TRANSFERIR IN ('S','N'))
)
/
INSERT INTO APP_SCHEMA.AJA_PERMISSAO(CD_USUARIO,SN_TRANSFERIR) VALUES ('ADMIN','N')
/
CREATE SEQUENCE APP_SCHEMA.AJA_AUDITORIA_SEQ
/
CREATE TABLE APP_SCHEMA.AJA_AUDITORIA (
 ID NUMBER PRIMARY KEY,
 DH_EVENTO TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CD_AUTOR VARCHAR2(128) NOT NULL,
 NM_AUTOR VARCHAR2(400) NOT NULL,
 ACAO VARCHAR2(60) NOT NULL,
 DETALHE VARCHAR2(2000) NOT NULL,
 CD_DOCUMENTO NUMBER,
 CD_ORIGEM VARCHAR2(128), NM_ORIGEM VARCHAR2(400),
 CD_DESTINO VARCHAR2(128), NM_DESTINO VARCHAR2(400),
 REQUEST_ID VARCHAR2(64)
)
/
CREATE OR REPLACE PACKAGE APP_SCHEMA.PKG_ASSINAJA_ACESSO AUTHID DEFINER AS
 PROCEDURE perfil(p_autor VARCHAR2, resultado OUT SYS_REFCURSOR);
 PROCEDURE setores(p_autor VARCHAR2, resultado OUT SYS_REFCURSOR);
 PROCEDURE usuarios(p_autor VARCHAR2, p_setor NUMBER, resultado OUT SYS_REFCURSOR);
 PROCEDURE permissao(p_autor VARCHAR2,p_usuario VARCHAR2,p_habilitar VARCHAR2,p_request VARCHAR2);
 PROCEDURE auditoria(p_autor VARCHAR2,p_antes NUMBER,resultado OUT SYS_REFCURSOR);
END;
/
CREATE OR REPLACE PACKAGE BODY APP_SCHEMA.PKG_ASSINAJA_ACESSO AS
 PROCEDURE ativo(p_usuario VARCHAR2) IS n NUMBER;
 BEGIN
  SELECT COUNT(*) INTO n FROM DBASGU.USUARIOS WHERE CD_USUARIO=p_usuario AND SN_ATIVO='S';
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20001,'Usuario inativo'); END IF;
 END;
 PROCEDURE perfil(p_autor VARCHAR2,resultado OUT SYS_REFCURSOR) IS
 BEGIN
  ativo(p_autor);
  OPEN resultado FOR SELECT u.CD_USUARIO,u.NM_USUARIO,
   CASE WHEN u.CD_USUARIO='ADMIN' THEN 'S' ELSE 'N' END MASTER,
   NVL(p.SN_TRANSFERIR,'N') TRANSFERIR
   FROM DBASGU.USUARIOS u LEFT JOIN APP_SCHEMA.AJA_PERMISSAO p ON p.CD_USUARIO=u.CD_USUARIO
   WHERE u.CD_USUARIO=p_autor AND u.SN_ATIVO='S';
 END;
 PROCEDURE setores(p_autor VARCHAR2,resultado OUT SYS_REFCURSOR) IS
 BEGIN
  ativo(p_autor);
  OPEN resultado FOR SELECT CD_SETOR,NM_SETOR FROM (
   SELECT s.CD_SETOR,s.NM_SETOR FROM USUARIO_BANCO.SETOR s WHERE s.SN_ATIVO='S'
   UNION ALL SELECT 0,'Sem setor ativo vinculado' FROM DUAL
  ) ORDER BY NM_SETOR,CD_SETOR;
 END;
 PROCEDURE usuarios(p_autor VARCHAR2,p_setor NUMBER,resultado OUT SYS_REFCURSOR) IS
 BEGIN
  ativo(p_autor);
  IF p_setor IS NULL OR p_setor<0 THEN RAISE_APPLICATION_ERROR(-20003,'Setor invalido'); END IF;
  OPEN resultado FOR SELECT u.CD_USUARIO,u.NM_USUARIO,t.NM_TIP_PRESTA,NVL(a.SN_TRANSFERIR,'N')
   FROM DBASGU.USUARIOS u
   LEFT JOIN USUARIO_BANCO.PRESTADOR p ON p.CD_PRESTADOR=u.CD_PRESTADOR
   LEFT JOIN USUARIO_BANCO.TIP_PRESTA t ON t.CD_TIP_PRESTA=p.CD_TIP_PRESTA
   LEFT JOIN APP_SCHEMA.AJA_PERMISSAO a ON a.CD_USUARIO=u.CD_USUARIO
   WHERE u.SN_ATIVO='S' AND (
    (p_setor=0 AND NOT EXISTS (SELECT 1 FROM USUARIO_BANCO.USUARIO_SETOR us JOIN USUARIO_BANCO.SETOR s ON s.CD_SETOR=us.CD_SETOR AND s.SN_ATIVO='S' WHERE us.NM_USUARIO=u.CD_USUARIO))
    OR EXISTS (SELECT 1 FROM USUARIO_BANCO.USUARIO_SETOR us JOIN USUARIO_BANCO.SETOR s ON s.CD_SETOR=us.CD_SETOR AND s.SN_ATIVO='S' WHERE us.NM_USUARIO=u.CD_USUARIO AND us.CD_SETOR=p_setor)
   ) ORDER BY t.NM_TIP_PRESTA NULLS LAST,u.NM_USUARIO,u.CD_USUARIO;
 END;
 PROCEDURE permissao(p_autor VARCHAR2,p_usuario VARCHAR2,p_habilitar VARCHAR2,p_request VARCHAR2) IS
  autor VARCHAR2(400); alvo VARCHAR2(400); anterior CHAR(1);
 BEGIN
  ativo(p_autor);
  IF p_autor<>'ADMIN' THEN RAISE_APPLICATION_ERROR(-20002,'Somente master'); END IF;
  ativo(p_usuario);
  IF p_habilitar IS NULL OR p_habilitar NOT IN ('S','N') THEN RAISE_APPLICATION_ERROR(-20003,'Permissao invalida'); END IF;
  SELECT NM_USUARIO INTO autor FROM DBASGU.USUARIOS WHERE CD_USUARIO=p_autor;
  SELECT SN_TRANSFERIR INTO anterior FROM APP_SCHEMA.AJA_PERMISSAO WHERE CD_USUARIO='ADMIN' FOR UPDATE;
  SELECT NM_USUARIO INTO alvo FROM DBASGU.USUARIOS WHERE CD_USUARIO=p_usuario;
  BEGIN SELECT SN_TRANSFERIR INTO anterior FROM APP_SCHEMA.AJA_PERMISSAO WHERE CD_USUARIO=p_usuario;
   EXCEPTION WHEN NO_DATA_FOUND THEN anterior:='N'; END;
  IF anterior=p_habilitar THEN RETURN; END IF;
  MERGE INTO APP_SCHEMA.AJA_PERMISSAO a USING (SELECT p_usuario usuario FROM DUAL) b ON (a.CD_USUARIO=b.usuario)
   WHEN MATCHED THEN UPDATE SET a.SN_TRANSFERIR=p_habilitar
   WHEN NOT MATCHED THEN INSERT (CD_USUARIO,SN_TRANSFERIR) VALUES(p_usuario,p_habilitar);
  INSERT INTO APP_SCHEMA.AJA_AUDITORIA(ID,CD_AUTOR,NM_AUTOR,ACAO,DETALHE,CD_DESTINO,NM_DESTINO,REQUEST_ID)
   VALUES(APP_SCHEMA.AJA_AUDITORIA_SEQ.NEXTVAL,p_autor,autor,'PERMISSAO',
    'Permissao de transferencia: '||anterior||' -> '||p_habilitar,p_usuario,alvo,p_request);
 END;
 PROCEDURE auditoria(p_autor VARCHAR2,p_antes NUMBER,resultado OUT SYS_REFCURSOR) IS
 BEGIN
  ativo(p_autor);
  OPEN resultado FOR SELECT * FROM (SELECT ID,
   TO_CHAR(SYS_EXTRACT_UTC(DH_EVENTO),'YYYY-MM-DD"T"HH24:MI:SS.FF3"Z"') DH_EVENTO,
   CD_AUTOR,NM_AUTOR,ACAO,DETALHE,
   CD_DOCUMENTO,CD_ORIGEM,NM_ORIGEM,CD_DESTINO,NM_DESTINO
   FROM APP_SCHEMA.AJA_AUDITORIA WHERE p_antes IS NULL OR ID<p_antes ORDER BY ID DESC) WHERE ROWNUM<=51;
 END;
END;
